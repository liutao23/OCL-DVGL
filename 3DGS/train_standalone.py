def gui_init(wish_host, wish_port):
    global gui_host, gui_port, gui_listener
    gui_host = wish_host
    gui_port = wish_port
    gui_listener.bind((gui_host, gui_port))
    gui_listener.listen()
    gui_listener.settimeout(0)

def gui_try_connect():
    global gui_conn, gui_addr, gui_listener
    try:
        gui_conn, gui_addr = gui_listener.accept()
        print(f"\nConnected by {gui_addr}")
        gui_conn.settimeout(None)
    except Exception as inst:
        pass
            
def gui_read():
    global gui_conn
    messageLength = gui_conn.recv(4)
    messageLength = int.from_bytes(messageLength, 'little')
    message = gui_conn.recv(messageLength)
    return json.loads(message.decode("utf-8"))

def gui_send(message_bytes, verify):
    global gui_conn
    if message_bytes != None:
        gui_conn.sendall(message_bytes)
    gui_conn.sendall(len(verify).to_bytes(4, 'little'))
    gui_conn.sendall(bytes(verify, 'ascii'))

def gui_receive():
    message = gui_read()

    width = message["resolution_x"]
    height = message["resolution_y"]

    if width != 0 and height != 0:
        try:
            do_training = bool(message["train"])
            fovy = message["fov_y"]
            fovx = message["fov_x"]
            znear = message["z_near"]
            zfar = message["z_far"]
            do_shs_python = bool(message["shs_python"])
            do_rot_scale_python = bool(message["rot_scale_python"])
            keep_alive = bool(message["keep_alive"])
            scaling_modifier = message["scaling_modifier"]
            world_view_transform = torch.reshape(torch.tensor(message["view_matrix"]), (4, 4)).cuda()
            world_view_transform[:,1] = -world_view_transform[:,1]
            world_view_transform[:,2] = -world_view_transform[:,2]
            full_proj_transform = torch.reshape(torch.tensor(message["view_projection_matrix"]), (4, 4)).cuda()
            full_proj_transform[:,1] = -full_proj_transform[:,1]
            custom_cam = MiniCam(width, height, fovy, fovx, znear, zfar, world_view_transform, full_proj_transform)
        except Exception as e:
            print("")
            traceback.print_exc()
            raise e
        return custom_cam, do_training, do_shs_python, do_rot_scale_python, keep_alive, scaling_modifier
    else:
        return None, None, None, None, None, None

